def forecast_attendance(model, test_df, trend, weekday_means):
    forecast_steps = len(test_df)

    # 1. Forecast residual component
    residual_forecast = model.forecast(steps=forecast_steps)

    # 2. Extend trend using last LOWESS trend value
    trend_forecast = np.repeat(trend[-1], forecast_steps)

    # 3. Add weekday cycle back
    test_cycle = test_df["DayOfWeek"].map(weekday_means).values

    # 4. Reconstruct attendance forecast
    final_forecast = trend_forecast + test_cycle + residual_forecast

    return final_forecast


