def clean_yankees_season(df, season):
    df = df.dropna(how="all").copy()

    # keep home games only
    df_home = df[df["Unnamed: 4"].isna()].copy()

    # clean attendance
    df_home["Attendance"] = pd.to_numeric(df_home["Attendance"], errors="coerce")
    df_home = df_home.dropna(subset=["Attendance"])
    df_home["Attendance"] = df_home["Attendance"].astype(int)

    # remove doubleheader marker like "(2)"
    df_home["Date"] = (
        df_home["Date"]
        .astype(str)
        .str.replace(r"\s\(\d+\)", "", regex=True)
    )

    # add year and convert date
    df_home["Date"] = pd.to_datetime(
        df_home["Date"] + f" {season}",
        format="%A %b %d %Y"
    )

    # features
    df_home["DayOfWeek"] = df_home["Date"].dt.day_name()
    df_home["Season"] = season

    # keep only needed columns
    df_home = df_home[["Date", "Attendance", "DayOfWeek", "Season"]]


    # reset index
    df_home = df_home.reset_index(drop=True)

    return df_home

